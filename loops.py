print("For Loop:")
for i in range(1, 6):
    print(i)
print("\nLoop through a list:")
fruits = ["Apple", "Banana", "Mango", "Orange"]
for fruit in fruits:
    print(fruit)
print("\nWhile Loop:")
count = 1
while count <= 5:
    print(count)
    count += 1
print("\nEven numbers:")
for number in range(1, 11):
    if number % 2 == 0:
        print(number)
